#!/usr/bin/env python3
"""Generate original synthetic GP3/GP4/GP5 fixtures; never reads user or third-party files."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import guitarpro

ROOT = Path(__file__).resolve().parents[3]
FIXTURES = ROOT / "fixtures/research/catalog-169"
GENERATED = FIXTURES / "generated"
EXPECTED = json.loads((FIXTURES / "expected-events.json").read_text(encoding="utf-8"))
EVENTS = EXPECTED["events"]
BASS = [(6, 0), (5, 3), (4, 5), (5, 3)] * 5


def add_notes(track, measures, events_by_bar):
    for measure_index, measure in enumerate(measures):
        voice = measure.voices[0]
        for beat_index, (string, fret) in enumerate(events_by_bar[measure_index]):
            beat = guitarpro.Beat(voice)
            beat.duration = guitarpro.Duration(guitarpro.Duration.quarter)
            beat.start = measure.start + beat_index * guitarpro.Duration.quarterTime
            beat.status = guitarpro.BeatStatus.normal
            note = guitarpro.Note(beat)
            note.string, note.value = string, fret
            note.type = guitarpro.NoteType.normal
            beat.notes.append(note)
            voice.beats.append(beat)


def build_song():
    song = guitarpro.Song()
    song.title = "GM169 Synthetic Guitar Events"
    song.subtitle = "Original synthetic fixture; no third-party composition"
    song.tempo = 96
    song.measureHeaders[0].timeSignature.numerator = 4
    song.measureHeaders[0].timeSignature.denominator = guitarpro.Duration(guitarpro.Duration.quarter)
    lead = song.tracks[0]
    lead.name = "Lead Guitar"
    lead.channel.channel, lead.channel.effectChannel = 0, 1
    rhythm = guitarpro.Track(song)
    rhythm.number = 2
    rhythm.name = "Rhythm Guitar"
    rhythm.channel.channel, rhythm.channel.effectChannel = 2, 3
    song.tracks.append(rhythm)
    for _ in range(4):
        song.newMeasure()
    start = guitarpro.Duration.quarterTime
    for header in song.measureHeaders:
        header.start = start
        start += header.length
    lead_by_bar = [[] for _ in range(5)]
    for event in EVENTS:
        lead_by_bar[event["bar"] - 1].append((event["string"], event["fret"]))
    add_notes(lead, lead.measures, lead_by_bar)
    add_notes(rhythm, rhythm.measures, [BASS[i:i + 4] for i in range(0, len(BASS), 4)])
    return song


def main():
    GENERATED.mkdir(parents=True, exist_ok=True)
    song = build_song()
    versions = {"gp3": (3, 0, 0), "gp4": (4, 0, 6), "gp5": (5, 1, 0)}
    records = []
    for ext, version in versions.items():
        target = GENERATED / f"gm169-synthetic.{ext}"
        guitarpro.write(song, target, version=version)
        parsed = guitarpro.parse(target)
        if len(parsed.tracks) != 2 or len(parsed.measureHeaders) != 5:
            raise RuntimeError(f"PyGuitarPro self-check failed: {ext}")
        notes = []
        for bar_index, measure in enumerate(parsed.tracks[0].measures, 1):
            for voice_index, voice in enumerate(measure.voices):
                for beat in voice.beats:
                    for note in beat.notes:
                        notes.append({"bar": bar_index, "voice": voice_index, "string": note.string,
                                      "fret": note.value, "midi": note.realValue,
                                      "duration": beat.duration.value})
        expected = [{"bar": e["bar"], "voice": e["voice"], "string": e["string"],
                     "fret": e["fret"], "midi": e["midi"], "duration": e["duration"]} for e in EVENTS]
        if notes != expected:
            raise RuntimeError(f"PyGuitarPro event self-check failed: {ext}")
        data = target.read_bytes()
        records.append({
            "id": f"gm169-synthetic-{ext}-001",
            "path": str(target.relative_to(ROOT)).replace("\\", "/"),
            "origin": f"Generated by PyGuitarPro 0.11 from expected-events.json; synthetic notes only",
            "permission": "Original synthetic work; no third-party score/audio/tab or private user data",
            "sha256": hashlib.sha256(data).hexdigest(),
            "format": f".{ext}",
            "formatVersion": ".".join(map(str, version)),
            "expectedEvents": "fixtures/research/catalog-169/expected-events.json",
            "expectedEventsSha256": hashlib.sha256((FIXTURES / "expected-events.json").read_bytes()).hexdigest(),
            "coverage": ["two guitar tracks", "explicit Lead Guitar selection", "standard tuning", "5 bars", "4/4", "quarter notes"],
            "generator": "PyGuitarPro 0.11; LGPL-3.0-only; fixtures only"
        })
    source = FIXTURES / "synthetic-score.alphatex"
    source_record = {
        "id": "gm169-synthetic-alphaTex-001",
        "path": str(source.relative_to(ROOT)).replace("\\", "/"),
        "origin": "Authored specifically for Guitar Mentor AI research #169; synthetic notes only",
        "permission": "Original synthetic work; no third-party score/audio/tab or private user data",
        "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "format": "alphaTex",
        "formatVersion": "alphaTab 1.8.4 alphaTex",
        "expectedEvents": "fixtures/research/catalog-169/expected-events.json",
        "expectedEventsSha256": hashlib.sha256((FIXTURES / "expected-events.json").read_bytes()).hexdigest(),
        "coverage": ["two guitar tracks", "explicit Lead Guitar selection", "standard tuning", "5 bars", "4/4"]
    }
    manifest = {"manifestVersion": 1, "fixtures": [source_record, *records],
                "unavailableSamples": [".gtp", ".gpx", ".gp (GP8)"]}
    (FIXTURES / "fixture-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"generated": records}, indent=2))


if __name__ == "__main__":
    main()
